"""Pre-signoff handoff bundle for a Pareto winner: SystemVerilog wrapper, SDC, UPF,
OpenROAD and Synopsys DC TCL, plus Verilator-lint and Yosys-equivalence scripts.

Everything is text generation. Nothing here runs a tool; the scripts are written for an
engineer (or CI) to run. A built-in structural lint checks the generated SystemVerilog.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
from pathlib import Path
from typing import Any

from chiplab.schemas.digital_twin import TWIN_DISCLAIMER, BlackBoxMacro

_SAFE = re.compile(r"[^A-Za-z0-9_.-]+")


def export_root() -> Path:
    return Path(os.environ.get("CHIPLAB_EXPORT_DIR", "chiplab_exports")).resolve()


def _ident(name: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]", "_", name)
    return s if re.match(r"[A-Za-z_]", s) else f"m_{s}"


def gen_systemverilog(params: dict[str, Any], blackboxes: list[BlackBoxMacro],
                      top: str = "soc_top") -> str:
    lanes = int(params.get("ucie_lanes", 0) or 0)
    lines = [
        "// Generated by ChipLab digital twin. Integration wrapper with stub tiles:",
        "// replace cva6_tile_stub with the real core (see chiplab IP catalog).",
        "`default_nettype none",
        "",
        "module cva6_tile_stub #(parameter int VLEN = 256, parameter int DLEN = 128,",
        "                        parameter int L1_KB = 32, parameter int L2_KB = 512) (",
        "  input  wire clk,",
        "  input  wire rst_n,",
        "  output wire busy",
        ");",
        "  assign busy = 1'b0;",
        "endmodule",
        "",
    ]
    for b in blackboxes:
        ports = ["  input  wire clk"]
        for p in b.pins:
            rng = f"[{p.width - 1}:0] " if p.width > 1 else ""
            d = {"input": "input ", "output": "output", "inout": "inout "}[p.direction]
            ports.append(f"  {d} wire {rng}{_ident(p.name)}")
        lines += [f"(* black_box *) module {_ident(b.name)} (", ",\n".join(ports), ");",
                  "endmodule", ""]
    lines += [
        f"module {top} #(",
        f"  parameter int NUM_CORES = {int(params['cores'])},",
        f"  parameter int VLEN = {int(params['vlen'])},",
        f"  parameter int DLEN = {int(params['dlen'])},",
        f"  parameter int L1_KB = {int(params['l1_kb'])},",
        f"  parameter int L2_KB = {int(params['l2_kb'])},",
        f"  parameter int UCIE_LANES = {lanes}",
        ") (",
        "  input  wire clk,",
        "  input  wire rst_n,",
    ]
    if lanes:
        lines += ["  input  wire [UCIE_LANES-1:0] ucie_rx,",
                  "  output wire [UCIE_LANES-1:0] ucie_tx,"]
    lines += ["  output wire busy", ");", "  wire [NUM_CORES-1:0] tile_busy;", "",
              "  genvar i;", "  generate", "    for (i = 0; i < NUM_CORES; i++) begin : g_tile",
              "      cva6_tile_stub #(.VLEN(VLEN), .DLEN(DLEN), .L1_KB(L1_KB), .L2_KB(L2_KB))",
              "        u_tile (.clk(clk), .rst_n(rst_n), .busy(tile_busy[i]));",
              "    end", "  endgenerate", "",
              "  assign busy = |tile_busy;"]
    if lanes:
        lines.append("  assign ucie_tx = ucie_rx;  // loopback placeholder")
    for b in blackboxes:
        conns = [".clk(clk)"]
        for p in b.pins:
            w = f"{_ident(b.name)}_{_ident(p.name)}"
            rng = f"[{p.width - 1}:0] " if p.width > 1 else ""
            lines.append(f"  wire {rng}{w};")
            if p.direction == "input":
                lines.append(f"  assign {w} = '0;")
            conns.append(f".{_ident(p.name)}({w})")
        lines.append(f"  {_ident(b.name)} u_{_ident(b.name)} ({', '.join(conns)});")
    lines += ["endmodule", "", "`default_nettype wire", ""]
    return "\n".join(lines)


def gen_sdc(params: dict[str, Any], blackboxes: list[BlackBoxMacro]) -> str:
    period_ns = 1.0 / float(params["freq_ghz"])
    out = [
        "# Generated by ChipLab. Clock from the digital-twin operating point.",
        f"create_clock -name clk -period {period_ns:.4f} [get_ports clk]",
        f"set_clock_uncertainty {0.05 * period_ns:.4f} [get_clocks clk]",
        f"set_input_delay {0.2 * period_ns:.4f} -clock clk [remove_from_collection "
        "[all_inputs] [get_ports clk]]",
        f"set_output_delay {0.2 * period_ns:.4f} -clock clk [all_outputs]",
        "set_false_path -from [get_ports rst_n]",
        f"set_max_transition {0.15 * period_ns:.4f} [current_design]",
    ]
    for b in blackboxes:
        inst = f"u_{_ident(b.name)}"
        for p in b.pins:
            if p.direction == "input" and p.setup_ps is not None:
                out.append(f"# {b.name}.{p.name}: datasheet setup {p.setup_ps} ps")
                out.append(f"set_max_delay {period_ns - p.setup_ps / 1000.0:.4f} -to "
                           f"[get_pins {inst}/{_ident(p.name)}*]")
            if p.direction == "output" and p.clk_to_q_ps is not None:
                out.append(f"# {b.name}.{p.name}: datasheet clk-to-q {p.clk_to_q_ps} ps")
                out.append(f"set_max_delay {period_ns - p.clk_to_q_ps / 1000.0:.4f} -from "
                           f"[get_pins {inst}/{_ident(p.name)}*]")
    return "\n".join(out) + "\n"


def gen_upf(params: dict[str, Any], blackboxes: list[BlackBoxMacro], top: str) -> str:
    vdd = float(params["vdd"])
    out = [
        "# Generated by ChipLab (UPF 2.1).",
        "create_power_domain PD_TOP -include_scope",
        "create_supply_port VDD", "create_supply_port VSS",
        "create_supply_net VDD -domain PD_TOP", "create_supply_net VSS -domain PD_TOP",
        "connect_supply_net VDD -ports VDD", "connect_supply_net VSS -ports VSS",
        "set_domain_supply_net PD_TOP -primary_power_net VDD -primary_ground_net VSS",
        f"add_port_state VDD -state {{ON {vdd:.3f}}} -state {{OFF off}}",
        "add_port_state VSS -state {ON 0.0}",
        "create_pst pst_top -supplies {VDD VSS}",
        "add_pst_state ON -pst pst_top -state {ON ON}",
    ]
    for b in blackboxes:
        inst = f"u_{_ident(b.name)}"
        pd = f"PD_{_ident(b.name).upper()}"
        out.append(f"create_power_domain {pd} -elements {{{inst}}}")
        for r in b.rails:
            net = f"{_ident(b.name)}_{_ident(r.name)}"
            out += [f"create_supply_port {net}", f"create_supply_net {net} -domain {pd}",
                    f"connect_supply_net {net} -ports {net}",
                    f"add_port_state {net} -state {{ON {r.voltage_v:.3f}}}"]
        if b.rails:
            out.append(f"set_domain_supply_net {pd} -primary_power_net "
                       f"{_ident(b.name)}_{_ident(b.rails[0].name)} -primary_ground_net VSS")
    return "\n".join(out) + "\n"


def gen_openroad(params: dict[str, Any], top: str, lef: list[str], lib: list[str]) -> str:
    lef = lef or ["<path/to/tech.lef>", "<path/to/stdcells.lef>"]
    lib = lib or ["<path/to/stdcells_typ.lib>"]
    util = float(params.get("utilization", 0.7)) * 100
    return "\n".join([
        "# Generated by ChipLab: OpenROAD flow skeleton (run: openroad -exit openroad_flow.tcl)",
        *[f"read_lef {p}" for p in lef], *[f"read_liberty {p}" for p in lib],
        f"read_verilog {top}_netlist.v  ;# synthesized netlist (Yosys/DC output)",
        f"link_design {top}", "read_sdc constraints.sdc",
        f"initialize_floorplan -utilization {util:.0f} -aspect_ratio 1.0 -core_space 10 "
        "-site <core_site>",
        "make_tracks", "place_pins -hor_layers <hlayer> -ver_layers <vlayer>",
        "global_placement -density 0.7", "detailed_placement", "clock_tree_synthesis",
        "repair_timing", "global_route", "detailed_route",
        "report_checks -path_delay max -fields {slew cap input nets fanout} > timing.rpt",
        "report_power > power.rpt", "write_def final.def", "",
    ])


def gen_dc(params: dict[str, Any], top: str, lib: list[str]) -> str:
    lib = lib or ["<path/to/stdcells_typ.db>"]
    return "\n".join([
        "# Generated by ChipLab: Synopsys Design Compiler script (dc_shell -f synopsys_dc.tcl)",
        f"set target_library [list {' '.join(lib)}]",
        "set link_library [concat * $target_library]",
        f"analyze -format sverilog {top}.sv", f"elaborate {top}", f"current_design {top}",
        "link", "source constraints.sdc", "load_upf power.upf", "compile_ultra",
        "report_timing -nets -max_paths 10 > dc_timing.rpt", "report_area > dc_area.rpt",
        "report_power > dc_power.rpt", f"write -format verilog -hierarchy -output "
        f"{top}_netlist.v", "",
    ])


def gen_verilator_lint(top: str) -> str:
    return "\n".join(["#!/usr/bin/env bash", "# Generated by ChipLab: Verilator lint "
                      "(not executed by ChipLab).", "set -euo pipefail",
                      f"verilator --lint-only -Wall -Wno-DECLFILENAME -Wno-UNUSEDSIGNAL "
                      f"--top-module {top} {top}.sv", ""])


def gen_yosys_equiv(top: str) -> str:
    return "\n".join([
        "# Generated by ChipLab: Yosys equivalence check RTL vs. synthesized netlist.",
        "# Run: yosys -s equiv_yosys.ys   (needs <cells_sim.v> for the netlist's cells)",
        f"read_verilog -sv {top}.sv", f"prep -top {top}", "rename -top gold", "design -stash gold",
        f"read_verilog {top}_netlist.v", "read_verilog <cells_sim.v>", f"prep -top {top}",
        "rename -top gate", "design -stash gate",
        "design -copy-from gold -as gold gold", "design -copy-from gate -as gate gate",
        "equiv_make gold gate equiv", "hierarchy -top equiv", "equiv_simple -seq 5",
        "equiv_induct", "equiv_status -assert", "",
    ])


def structural_lint(sv: str, testbench: bool = False) -> list[str]:
    """Cheap deterministic checks on generated SystemVerilog (not a replacement for Verilator)."""
    issues = []
    code = re.sub(r'"(?:[^"\\\n]|\\.)*"', '""', sv)
    code = re.sub(r"//[^\n]*", "", code)
    code = re.sub(r"/\*.*?\*/", "", code, flags=re.S)
    mods = re.findall(r"\bmodule\s+(\w+)", code)
    ends = len(re.findall(r"\bendmodule\b", code))
    if len(mods) != ends:
        issues.append(f"module/endmodule mismatch: {len(mods)} vs {ends}")
    if len(set(mods)) != len(mods):
        issues.append("duplicate module names")
    for ch_open, ch_close in ("()", "[]", "{}"):
        if code.count(ch_open) != code.count(ch_close):
            issues.append(f"unbalanced {ch_open}")
    if len(re.findall(r"\bbegin\b", code)) != len(re.findall(r"\bend\b", code)):
        issues.append("begin/end mismatch")
    for kw, opener in (("generate", r"\bgenerate\b"), ("case", r"\bcase[zx]?\b"),
                       ("function", r"\bfunction\b"), ("task", r"\btask\b")):
        if len(re.findall(opener, code)) != len(re.findall(rf"\bend{kw}\b", code)):
            issues.append(f"{kw}/end{kw} mismatch")
    for m in re.finditer(r"\bmodule\s+(\w+)[^;]*?\((.*?)\);", code, flags=re.S):
        names = re.findall(r"(?:input|output|inout)\s+wire\s+(?:\[[^\]]*\]\s*)?(\w+)", m.group(2))
        if len(names) != len(set(names)):
            issues.append(f"{m.group(1)}: duplicate port names")
    synth = re.sub(r"`ifndef\s+SYNTHESIS\b.*?`endif", "", code, flags=re.S)
    if not testbench and re.search(r"\binitial\b", synth):
        issues.append("initial block outside `ifndef SYNTHESIS in synthesizable code")
    return issues


def build_bundle(point: dict[str, Any], run_id: str, rank: int,
                 blackboxes: list[BlackBoxMacro] | None = None, output_name: str | None = None,
                 lef_paths: list[str] | None = None, lib_paths: list[str] | None = None,
                 top: str = "soc_top") -> dict[str, Any]:
    """Write the bundle under CHIPLAB_EXPORT_DIR/<output_name> and return a manifest."""
    blackboxes = blackboxes or []
    params = point["params"]
    root = export_root()
    name = _SAFE.sub("_", output_name or f"{run_id}_rank{rank}").strip("._") or "bundle"
    out = (root / name).resolve()
    if root not in out.parents:
        raise PermissionError("output_name must stay inside the export directory")
    out.mkdir(parents=True, exist_ok=True)
    top = _ident(top)
    sv = gen_systemverilog(params, blackboxes, top)
    lint = structural_lint(sv)
    files = {
        f"{top}.sv": sv,
        "constraints.sdc": gen_sdc(params, blackboxes),
        "power.upf": gen_upf(params, blackboxes, top),
        "openroad_flow.tcl": gen_openroad(params, top, lef_paths or [], lib_paths or []),
        "synopsys_dc.tcl": gen_dc(params, top, lib_paths or []),
        "lint_verilator.sh": gen_verilator_lint(top),
        "equiv_yosys.ys": gen_yosys_equiv(top),
        "structural_lint.txt": "\n".join(lint) + "\n" if lint else "PASS: no structural issues\n",
    }
    manifest: dict[str, Any] = {
        "run_id": run_id, "rank": rank, "top": top, "params": params,
        "metrics": point.get("metrics"), "robustness": point.get("robustness"),
        "blackboxes": [b.model_dump(mode="json") for b in blackboxes],
        "disclaimer": TWIN_DISCLAIMER + " RTL tiles are stubs; scripts are not executed by "
                      "ChipLab.",
        "files": {},
    }
    readme = (f"# Handoff bundle: {run_id} rank {rank}\n\n"
              f"Operating point: {params['freq_ghz']} GHz @ {params['vdd']} V, node "
              f"{params['node']}, {params['cores']} cores.\n\n"
              "1. `bash lint_verilator.sh` - lint the wrapper\n"
              "2. Synthesize: `dc_shell -f synopsys_dc.tcl` (or Yosys)\n"
              "3. `yosys -s equiv_yosys.ys` - RTL vs netlist equivalence\n"
              "4. `openroad -exit openroad_flow.tcl` - place and route\n"
              "5. Feed timing.rpt back with calibrate_from_eda_report.\n")
    files["README.md"] = readme
    for fname, text in files.items():
        (out / fname).write_text(text)
        manifest["files"][fname] = hashlib.sha256(text.encode()).hexdigest()
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, default=str))
    return {"directory": str(out), "files": sorted([*files, "manifest.json"]),
            "structural_lint": lint or ["PASS"], "manifest": manifest}
