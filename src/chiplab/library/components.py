def get_component_defaults(category: str, name: str) -> Optional[Dict[str, Any]]:
    """Return the default component spec for a given category and name."""
    library = {
        k: v for k, v in COMPONENT_LIBRARY.items()
        if v.get("category") == category and k.lower() == name.lower()
    }
    if library:
        return list(library.values())[0]
    return None


def list_components(category: str | None = None) -> List[str]:
    """List component names, optionally filtered by category."""
    if category:
        return [k for k, v in COMPONENT_LIBRARY.items() if v.get("category") == category]
    return list(COMPONENT_LIBRARY.keys())