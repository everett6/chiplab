"""OpenROAD adapter for ChipLab solver integration.

OpenROAD adapter supports the full ASIC flow: floorplan, placement,
clock tree synthesis, routing, and static timing analysis.

Input: LEF/DEF, GDS, SDC constraints, Verilog/RTL
Output: Placed and routed GDS, timing reports, placement reports
GPU support: optional acceleration for placement/routing algorithms
"""

from __future__ import annotations

import subprocess
import tempfile
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from chiplab.schemas.common import TrackedValue, Provenance
from chiplab.schemas.simulation import SimulationConfig, SimulationResult
from chiplab.schemas.design import DesignSpec
from chiplab.schemas.common import FidelityLevel
from .base import SolverAdapter


class OpenROADAdapter(SolverAdapter):
    """OpenROAD adapter for ASIC flow: floorplan, placement, CTS, routing, STA.

    OpenROAD is an open-source flow for ASIC implementation including:
    - Floorplan planning
    - Placement
    - Clock tree synthesis (CTS)
    - Routing
    - Static timing analysis (STA)

    Input: LEF/DEF, GDS, SDC, Verilog/RTL
    Output: Placed and routed GDS, timing reports, power reports
    GPU support: optional acceleration
    """

    name: str = "openroad"
    use_gpu: bool = True
    fidelity: FidelityLevel = FidelityLevel.SPECIALIZED
    executable: str = "openroad"

    def _get_supported_physics(self) -> List[str]:
        return ["electrical"]

    def _get_supported_scales(self) -> List[str]:
        return ["system", "board", "wafer"]

    def prepare_input(
        self, design: DesignSpec, workload: Any, config: SimulationConfig
    ) -> Tuple[str, Dict[str, TrackedValue]]:
        """Prepare OpenROAD flow and return (work_dir, parameter_map).

        Args:
            design: The ChipLab design specification
            workload: The workload/simulation configuration
            config: Simulation configuration

        Returns:
            Tuple of (working_directory_path, parameter_map)
        """
        tmpdir = tempfile.mkdtemp(prefix="chiplab_openroad_")
        tmp = Path(tmpdir)

        # Create OpenROAD project directory structure
        src_dir = tmp / "src"
        src_dir.mkdir()
        flow_dir = tmp / "flow"
        flow_dir.mkdir()
        run_dir = tmp / "run"
        run_dir.mkdir()

        # Write design files based on design specification
        self._write_openroad_files(design, src_dir, flow_dir, run_dir)

        # Build parameter map from design/workload
        param_map: Dict[str, TrackedValue] = {}
        if hasattr(design, "chiplets") and design.chiplets:
            for i, chiplet in enumerate(design.chiplets):
                param_map[f"chiplet_{i}_placement"] = TrackedValue(
                    value=chiplet.area_mm2,
                    unit="mm2",
                    provenance=Provenance.ASSUMED,
                )

        # Add workload parameters
        if workload:
            for key, value in workload.items():
                if isinstance(value, (int, float, str, bool)):
                    param_map[key] = TrackedValue(
                        value=value,
                        unit=None,
                        provenance=Provenance.ASSUMED,
                    )

        return str(run_dir), param_map

    def _write_openroad_files(
        self, design: DesignSpec, src_dir: Path, flow_dir: Path, run_dir: Path
    ) -> None:
        """Write OpenROAD design and constraint files.

        Args:
            design: The ChipLab design specification
            src_dir: Source directory path
            flow_dir: Flow directory path
            run_dir: Run directory path
        """
        # Write Liberty cell library (simplified)
        lib_path = src_dir / "celllib.lib"
        with open(lib_path, "w") as f:
            f.write("* Cell library generated by ChipLab\n")
            f.write("cell(inv1)\n")
            f.write("area 10\n")
            f.write("pin in\n")
            f.write("pin out\n")
            f.write("end\n")

        # Write SDC constraints
        sdc_path = src_dir / "design.sdc"
        with open(sdc_path, "w") as f:
            f.write("* ChipLab generated SDC constraints\n")
            f.write("create_clock -name clk -period 10 [get_clocks clk]\n")
            f.write("set_output_delay -related clk -from [get_ports in] -to [get_ports out]\n")

        # Write Verilog source
        verilog_path = src_dir / "design.sv"
        with open(verilog_path, "w") as f:
            if design.chiplets:
                f.write("module chiplab_design();\n")
                for i in range(len(design.chiplets)):
                    f.write(f"    input [{31}:0] chiplet_{i}_in;\n")
                f.write("    output [{31}:0] result;\n")
                f.write("    assign result = |chiplet_{0}_in;\n")
                f.write("endmodule\n")
            else:
                f.write("module test();\n")
                f.write("    reg [31:0] a;\n")
                f.write("    wire [31:0] sum;\n")
                f.write("    assign sum = a + 32'h1234;\n")
                f.write("endmodule\n")

        # Write DEF placeholder
        def_path = run_dir / "design.def"
        with open(def_path, "w") as f:
            f.write("* OpenROAD generated DEF placeholder\n")
            f.write("design_name chiplab\n")
            f.write("source 0 0\n")
            f.write("units micrometers\n")
            f.write("0 0 1000 1000\n")

        # Write GDS placeholder
        gds_path = run_dir / "design.gds"
        with open(gds_path, "w") as f:
            f.write("* OpenROAD generated GDS placeholder\n")

    def run(
        self, input_path: str, resources: Optional[Dict[str, Any]] = None
    ) -> subprocess.CompletedProcess:
        """Run OpenROAD ASIC flow.

        Args:
            input_path: Path to the working directory
            resources: Optional resource limits (cpu, memory, gpu, timeout)

        Returns:
            CompletedProcess from running OpenROAD
        """
        run_dir = Path(input_path)

        # OpenROAD flow typically uses the openroad CLI or TCL scripting
        cmd = [
            self.executable,
            "-def",
            str(run_dir / "design.def"),
            "-gds",
            str(run_dir / "design.gds"),
            "-sdc",
            str(run_dir / "src" / "design.sdc"),
        ]

        # Add GPU acceleration if requested and available
        if resources and resources.get("gpu", False):
            cmd.extend(["-gpu", "1"])

        # Set timeout for the full flow
        timeout = resources.get("timeout", 600) if resources else 600

        try:
            process = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=timeout,
            )
            return process
        except subprocess.TimeoutExpired as e:
            raise RuntimeError(
                f"OpenROAD flow timed out after {timeout}s: {e}"
            )
        except FileNotFoundError:
            raise RuntimeError(
                f"OpenROAD executable not found: {self.executable}. "
                "Please install OpenROAD."
            )

    def parse_output(
        self, process: subprocess.CompletedProcess
    ) -> Dict[str, TrackedValue]:
        """Parse OpenROAD output for ASIC flow results.

        Args:
            process: The CompletedProcess from running OpenROAD

        Returns:
            Dictionary mapping output parameter names to TrackedValue objects
        """
        results: Dict[str, TrackedValue] = {}

        if process.returncode != 0:
            return self.handle_error(
                RuntimeError(
                    f"OpenROAD failed with return code {process.returncode}"
                )
            )

        output = process.stdout

        # Parse timing reports
        for line in output.split("\n"):
            line = line.strip()

            # Parse negative slack
            if "ns" in line and (("slack" in line.lower()) or ("negative" in line.lower())):
                try:
                    import re
                    match = re.search(r"([-+]?\d+\.?\d*)\s*ns", line)
                    if match:
                        slack = float(match.group(1))
                        results["timing_slack_ns"] = TrackedValue(
                            value=slack,
                            unit="ns",
                            provenance=Provenance.MEASURED,
                        )
                except (ValueError, IndexError):
                    pass

            # Parse total negative slack
            if "TNS" in line or "negative_slack" in line.lower():
                try:
                    parts = line.split()
                    for i, part in enumerate(parts):
                        if part.replace(".", "", 1).isdigit() or (
                            part.startswith("-") and part[1:].replace(".", "", 1).isdigit()
                        ):
                            results["tns_ns"] = TrackedValue(
                                value=float(parts[i]),
                                unit="ns",
                                provenance=Provenance.MEASURED,
                            )
                            break
                except (ValueError, IndexError):
                    pass

            # Parse WNS (worst negative slack)
            if "WNS" in line:
                try:
                    parts = line.split()
                    for i, part in enumerate(parts):
                        if part.replace(".", "", 1).isdigit() or (
                            part.startswith("-") and part[1:].replace(".", "", 1).isdigit()
                        ):
                            results["wns_ns"] = TrackedValue(
                                value=float(parts[i]),
                                unit="ns",
                                provenance=Provenance.MEASURED,
                            )
                            break
                except (ValueError, IndexError):
                    pass

        # Parse power reports
        for line in output.split("\n"):
            line = line.strip()
            if "Power" in line and "mW" in line:
                try:
                    parts = line.split()
                    for i, part in enumerate(parts):
                        if part.replace(".", "", 1).isdigit() and "mW" in parts[i - 1] if i > 0 else False:
                            results["power_mw"] = TrackedValue(
                                value=float(parts[i - 1].replace("mW", "").strip()),
                                unit="mW",
                                provenance=Provenance.MEASURED,
                            )
                            break
                except (ValueError, IndexError):
                    pass

        # Parse area reports
        if "area" in output.lower() and "um" in output.lower():
            try:
                # Look for area in square micrometers
                import re
                match = re.search(r"(\d+\.?\d*)\s*um\s*area", output, re.IGNORECASE)
                if match:
                    results["cell_area_um2"] = TrackedValue(
                        value=float(match.group(1)),
                        unit="um2",
                        provenance=Provenance.MEASURED,
                    )
            except (ValueError, IndexError):
                pass

        return results

    def cleanup(self, input_path: str) -> None:
        """Clean up OpenROAD temporary files.

        Args:
            input_path: Path to the working directory to clean up
        """
        base = Path(input_path)
        if base.is_dir():
            # Remove generated files
            for pattern in ["*.def", "*.gds", "*.sdc", "*.lib", "*.v"]:
                for f in base.glob(pattern):
                    try:
                        f.unlink()
                    except OSError:
                        pass
            # Remove cache/log files
            for pattern in ["*.log", "*.cmd", "*.tcl"]:
                for f in base.glob(pattern):
                    try:
                        f.unlink()
                    except OSError:
                        pass

    def get_capability(self) -> "SolverCapability":
        """Get OpenROAD-specific capability information.

        Returns:
            SolverCapability with OpenROAD-specific details
        """
        from chiplab.solvers.registry import SolverCapability, SolverSpec

        return SolverCapability(
            spec=SolverSpec(
                name=self.name,
                version=self._get_version(),
                executable=self.executable,
                fidelity=self.fidelity,
                supported_physics=self._get_supported_physics(),
                supported_scales=self._get_supported_scales(),
                input_formats=["lef", "def", "gds", "sdc", "verilog"],
                output_formats=["def", "gds", "timing_reports", "power_reports",
                                "place_reports"],
            ),
            requires_gpu=self._requires_gpu(),
            supported_analysis_types=[
                "floorplan",
                "placement",
                "cts",
                "routing",
                "sta",
                "power_analysis",
            ],
        )

    def _get_version(self) -> str:
        """Get OpenROAD version."""
        try:
            result = subprocess.run(
                [self.executable, "--version"], capture_output=True, text=True
            )
            if result.returncode == 0:
                for line in result.stdout.split("\n"):
                    if "OpenROAD" in line:
                        import re
                        match = re.search(r"(\d+\.\d+(?:\.\d+)?)", line)
                        if match:
                            return match.group(1)
        except Exception:
            pass
        return "2023.09"

    def _requires_gpu(self) -> bool:
        """Check if OpenROAD was built with GPU acceleration support."""
        try:
            result = subprocess.run(
                [self.executable, "-h"], capture_output=True, text=True
            )
            return "gpu" in result.stdout.lower() or "cuda" in result.stdout.lower()
        except Exception:
            return False